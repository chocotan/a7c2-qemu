static uint16_t le16(const unsigned char *p) {
    return (uint16_t)(p[0] | (uint16_t)p[1] << 8);
}

int cp_parameter_batch_init(struct cp_parameter_batch *owner, bool enabled) {
    if (!owner) return -EINVAL;
    memset(owner, 0, sizeof(*owner));
    owner->owner_pid = getpid();
    owner->enabled = enabled;
    return 0;
}

int cp_parameter_batch_stage(struct cp_parameter_batch *owner, uint32_t source,
                             uint32_t target, const void *input, size_t size) {
    const unsigned char *p = input;
    uintptr_t start = (uintptr_t)input, output = (uintptr_t)owner;
    size_t end = 8;
    if (!owner || !input) return -EINVAL;
    if (!owner->enabled) return -EACCES;
    if (owner->owner_pid != getpid()) return -ECHILD;
    if (owner->staged) return -EBUSY;
    if (source != CP_PARAMETER_BATCH_SOURCE || target != CP_PARAMETER_BATCH_TARGET)
        return -EPERM;
    if (size != CP_PARAMETER_BATCH_BYTES) return -EMSGSIZE;
    if (start > UINTPTR_MAX - size || output > UINTPTR_MAX - sizeof(*owner))
        return -EINVAL;
    if (start < output + sizeof(*owner) && output < start + size) return -EINVAL;
    if (p[0] != 5 || le16(p + 2) != 0x4063) return -EPROTO;
    for (size_t i = 0; i < CP_PARAMETER_BATCH_SLOTS; i++) {
        const struct cp_parameter_batch_slot *s = &cp_parameter_batch_slots[i];
        if (s->offset != end || s->size < 8 || s->size > size - end)
            return -EINVAL;
        if (p[end] != 5 || le16(p + end + 2) != s->opcode) return -EPROTO;
        end += s->size;
    }
    if (end != size) return -EINVAL;
    memcpy(owner->bytes, p, size);
    memset(owner->semantic_consumed, 0, sizeof(owner->semantic_consumed));
    /* shortcut: business setters remain unimplemented; stage cannot publish. */
    owner->semantic_applied = false;
    owner->staged = true;
    return CP_PARAMETER_BATCH_STAGED;
}
